package packages;
public class PackageDemo {

    private int x;
    private int y;

    public void setData(int p , int q)
    {
        x=p;
        y=q;
    }

   public void display()
    {
        System.out.println("value of x :- " + x);
        System.out.println("Value of y :-  " + y);
    }
}
